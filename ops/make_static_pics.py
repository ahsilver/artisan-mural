# Makes small WebP versions of the built-in pictures into app/public/s and writes app/src/lib/static-pics.gen.ts.
# Run: python3 ops/make_static_pics.py  (re-run when a built-in picture changes)

from PIL import Image
import hashlib, os, json, io, base64
APP='/home/user/tab/work/artisan-copy/app/'
out=APP+'public/s/'; os.makedirs(out,exist_ok=True)
for f in os.listdir(out): os.remove(out+f)
srcs={}
for f in sorted(os.listdir(APP+'src/assets')):
    if f.endswith('.jpg') and (f.startswith('design-') or f.startswith('showcase-before')): srcs[f.rsplit('.',1)[0]]=APP+'src/assets/'+f
for f in ['hero-mural.webp','showcase-after.webp','design-cranes-blush.webp','design-cranes-ivory.webp','design-cranes-midnight.webp']:
    srcs[f.rsplit('.',1)[0]]=APP+'public/media/'+f
man={}
for name,path in srcs.items():
    im=Image.open(path).convert('RGB'); W,H=im.size
    ws=[w for w in [320,480,720,1080,1440] if w<=W*1.02] or [W]
    files=[]
    for w in ws:
        r=im.resize((w,round(H*w/W)),Image.LANCZOS); b=io.BytesIO(); r.save(b,'WEBP',quality=74 if w<1000 else 78,method=6)
        h=hashlib.sha1(b.getvalue()).hexdigest()[:8]; fn=f'{name}-{w}-{h}.webp'
        open(out+fn,'wb').write(b.getvalue()); files.append(fn)
    t=im.resize((16,max(1,round(H*16/W)))); b=io.BytesIO(); t.save(b,'WEBP',quality=40)
    man[name]={'w':ws,'f':files,'ar':round(W/H,3),'lq':'data:image/webp;base64,'+base64.b64encode(b.getvalue()).decode()}
open(APP+'src/lib/static-pics.gen.ts','w').write('// Generated by ops/make_static_pics.py: small WebP versions of the built-in pictures (public/s/).\nexport const STATIC_PICS: Record<string, { w: number[]; f: string[]; ar: number; lq: string }> = '+json.dumps(man)+';\n')